def parse(text):
    parts = []
    for block in re.split(r'\n  \{\n', text)[1:]:
        slug = re.search(r'slug: "([a-z-]+)"', block)
        if not slug:
            continue
        sides = {}
        for side in ('common', 'left', 'right'):
            m = re.search(side + r': \[([\s\S]*?)\]', block)
            sides[side] = re.findall(r'"([^"]+)"', m.group(1)) if m else []
        parts.append((slug.group(1), sides))
    return parts


def main():
    source = Path(sys.argv[1])
    commit = subprocess.run(['git', '-C', str(source), 'rev-parse', 'HEAD'],
                            capture_output=True, text=True, check=True).stdout.strip()
    if commit != SOURCE_COMMIT:
        sys.exit(f'expected react-native-body-highlighter {SOURCE_COMMIT}, found {commit}')
    views = {}
    for view, file, mapping in (('front', 'bodyFront.ts', FRONT), ('back', 'bodyBack.ts', BACK)):
        body, regions = [], {}
        for slug, sides in parse((source / 'assets' / file).read_text()):
            for side, paths in sides.items():
                for i, d in enumerate(paths):
                    body.append(d)
                    region = mapping.get(slug)
                    if slug == 'obliques' and i in SERRATUS:
                        region = None
                    if slug == 'upper-back' and i == LATS.get(side):
                        region = 'lats'
                    if region:
                        regions.setdefault(region, []).append(d)
        views[view] = {'viewBox': FRAMES[view], 'body': ' '.join(body),
                       'regions': {k: ' '.join(v) for k, v in sorted(regions.items())}}
    notice = '\n'.join(' * ' + line if line else ' *' for line in LICENSE.splitlines())
    text = (
        '/**\n'
        ' * Male front/back body figure for the Muscles views, generated by\n'
        ' * scripts/catalog/body_paths.py from react-native-body-highlighter\n'
        f' * (https://github.com/HichamELBSI/react-native-body-highlighter, {commit[:7]}).\n'
        ' * Paths are unchanged, only grouped into regions. Never edited by hand.\n'
        ' *\n'
        f'{notice}\n'
        ' */\n'
        f'export const bodyViews = {json.dumps(views)} as const;\n'
    )
    formatted = subprocess.run(
        ['node', str(ROOT / 'node_modules/prettier/bin/prettier.cjs'), '--stdin-filepath', str(OUT)],
        input=text, text=True, capture_output=True, check=True, cwd=ROOT,
    ).stdout
    OUT.write_text(formatted)
    print({view: sorted(views[view]['regions']) for view in views})


if __name__ == '__main__':
    main()
