# Source slug -> Ember region, per view. Slugs not listed (head, hair, neck, hands, feet, knees,
# ankles, tibialis; the front view's trapezius wedges and calf slivers) are plain body.
FRONT = {'chest': 'chest', 'deltoids': 'frontCap', 'biceps': 'biceps', 'triceps': 'triceps',
         'forearm': 'forearms', 'abs': 'abs', 'obliques': 'obliques', 'quadriceps': 'quads',
         'adductors': 'adductors'}
BACK = {'trapezius': 'traps', 'deltoids': 'backCap', 'upper-back': 'upperBack',
        'lower-back': 'lowerBack', 'triceps': 'triceps', 'forearm': 'forearms', 'gluteal': 'glutes',
        'hamstring': 'hamstrings', 'adductors': 'adductors', 'calves': 'calves'}
# Sub-path indices (per side), chosen from their bounding boxes and checked by eye.
SERRATUS = {0, 1, 2, 3}  # obliques: the upper finger slivers are serratus anterior, plain body
LATS = {'left': 1, 'right': 2}  # upper-back: the tall wedge; the two arcs stay Upper back
# Tight frames around each figure, with room for the body outline stroke.
FRAMES = {'front': '40 84 648 1272', 'back': '760 84 648 1272'}

